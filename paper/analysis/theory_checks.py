#!/usr/bin/env python3
"""Numerical checks of the propositions in the Traze paper.

Run from the repository root:

    uv run --no-project --with numpy python paper/analysis/theory_checks.py

Writes paper/generated/theory_numbers.tex (LaTeX macros) and prints each check.
"""

import math
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[2] / "paper" / "generated" / "theory_numbers.tex"
RNG = np.random.default_rng(20261012)


def horizon_exact(t0, balance):
    """Rounds a passive agent stays solvent from round t0 when aging is (t-1)."""
    a = 2 * t0 - 3
    return math.floor((-a + math.sqrt(a * a + 8 * balance)) / 2)


def horizon_brute(t0, balance):
    k, spent = 0, 0
    while spent + (t0 - 1 + k) <= balance:
        spent += t0 - 1 + k
        k += 1
    return k


def check_red_queen():
    for t0 in range(2, 120):
        for b in range(0, 6000, 7):
            assert horizon_exact(t0, b) == horizon_brute(t0, b), (t0, b)
    k = horizon_exact(35, 800)
    lin = 800 / 34
    print(f"[Prop 1] closed form matches brute force; t0=35,B=800: exact={k}, linear={lin:.1f}")
    return {"RQExact": k, "RQLinear": f"{lin:.1f}", "RQOver": f"{100 * (lin / k - 1):.0f}"}


def equilibrium_bids(n, value, size):
    u = RNG.random(size)
    return value * (1 - (1 - u) ** (n - 1))


def check_contest():
    value = 1.0
    out = {}
    for n in (2, 5, 10, 50):
        bids = equilibrium_bids(n, value, (200_000, n))
        mean_spend = bids.mean()
        losers = bids.argmin(axis=1)
        survive = np.ones_like(bids, dtype=bool)
        survive[np.arange(len(bids)), losers] = False
        payoff = (value * survive - bids).mean()
        # Deviation payoffs against n-1 equilibrium opponents.
        opp = equilibrium_bids(n, value, (200_000, n - 1))
        dev = []
        for x in np.linspace(0, 1.2, 13):
            p_survive = (opp.min(axis=1) < x).mean()
            dev.append(value * p_survive - x)
        print(
            f"[Prop 2] n={n:2d}: mean spend {mean_spend:.4f} (theory {(n - 1) / n:.4f}); "
            f"mean payoff {payoff:+.4f}; max deviation payoff {max(dev):+.4f}"
        )
        assert abs(mean_spend - (n - 1) / n) < 5e-3 and abs(payoff) < 5e-3 and max(dev) < 5e-3
    return out


def collapse_prob(n, ratio, broad):
    """P(collapse after one equilibrium round) when every agent's solvency
    margin is m = ratio * V. Literal rule: exactly one solvent survivor (K=2);
    broad rule: at most one (K<=2), where K = #{i: x_i < m}."""
    f = 1 - (1 - min(ratio, 1.0)) ** (1 / (n - 1))
    pk = [math.comb(n, k) * f**k * (1 - f) ** (n - k) for k in range(3)]
    return sum(pk) if broad else pk[2]


def check_collapse():
    out = {}
    for n in (10, 50):
        for ratio in (0.25, 1.0, 2.0):
            x = equilibrium_bids(n, 1.0, (200_000, n))
            k = (x < ratio).sum(axis=1)
            mc_lit, mc_broad = (k == 2).mean(), (k <= 2).mean()
            th_lit, th_broad = collapse_prob(n, ratio, False), collapse_prob(n, ratio, True)
            print(
                f"[Cor 2.2] n={n}, m/V={ratio}: literal {th_lit:.3f} (MC {mc_lit:.3f}); "
                f"broad {th_broad:.3f} (MC {mc_broad:.3f})"
            )
            assert abs(mc_lit - th_lit) < 6e-3 and abs(mc_broad - th_broad) < 6e-3
    grid = np.linspace(0.01, 1, 400)
    best = max(grid, key=lambda r: collapse_prob(50, r, False))
    out["CollapseLitMaxFifty"] = f"{collapse_prob(50, best, False):.2f}"
    out["CollapseLitArgmaxFifty"] = f"{best:.2f}"
    out["CollapseBroadQuarterTen"] = f"{collapse_prob(10, 0.25, True):.3f}"
    out["CollapseBroadQuarterFifty"] = f"{collapse_prob(50, 0.25, True):.3f}"
    print(f"[Cor 2.2] n=50 literal-rule maximum {out['CollapseLitMaxFifty']} at m/V={out['CollapseLitArgmaxFifty']}")
    return out


def check_power():
    from statistics import NormalDist

    z = NormalDist().inv_cdf
    p1, p2 = 0.2, 0.5
    pbar = (p1 + p2) / 2
    n = (z(0.975) * math.sqrt(2 * pbar * (1 - pbar)) + z(0.8) * math.sqrt(p1 * (1 - p1) + p2 * (1 - p2))) ** 2 / (p1 - p2) ** 2
    print(f"[Power] two-proportion test 0.2 vs 0.5, alpha .05, power .8: n = {n:.1f} per arm")
    return {"PowerN": math.ceil(n)}


def check_viability():
    beta, tau, sigma = 10, 50, 50
    top, mid = beta + tau, beta - sigma
    print(f"[Prop 8] reference viability: top tier needs >= {top}/interval, middle tier >= {mid}/interval")
    return {"ViaTop": top, "ViaMid": mid, "SandbagGain": tau + sigma}


def main():
    macros = {}
    macros.update(check_red_queen())
    macros.update(check_contest())
    macros.update(check_collapse())
    macros.update(check_power())
    macros.update(check_viability())
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w") as f:
        f.write("% Generated by paper/analysis/theory_checks.py -- do not edit by hand.\n")
        for k, v in macros.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print("all checks passed")


if __name__ == "__main__":
    main()
